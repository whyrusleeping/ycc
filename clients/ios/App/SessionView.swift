import SwiftUI
import UIKit
import YccKit

/// Read-only-plus-interactive session transcript feed projected from the event
/// log. Live sessions
/// stream via `Subscribe`; persisted sessions load once via
/// `GetSessionTranscript`. The heavy lifting (folding, reconnect, actions) lives
/// in ``SessionViewModel``; this view is a thin renderer.
///
/// Interactions: a sticky input bar (`SendInput`), an answer sheet
/// for `ask_user` (`AnswerQuestion`/`AnswerQuestions`), and an overflow menu for
/// interrupt/resume/stop. Chrome (banners) reflects the derived session phase.
struct SessionView: View {
    @Environment(AppModel.self) private var app
    @Environment(HomeRouter.self) private var router
    @Environment(\.scenePhase) private var scenePhase

    @State private var model: SessionViewModel
    /// Focus mirror for the composer field (a plain Bool rather than
    /// `@FocusState` because the field is the UIKit-backed `ComposerTextField`,
    /// which exists so an image on the clipboard can be pasted in-field).
    @State private var composerFocused = false
    /// Keyboard overlap for manual avoidance of the bottom chrome — see
    /// KeyboardObserver for why the automatic keyboard safe area is not used.
    @StateObject private var keyboard = KeyboardObserver()
    /// Whether new content should keep the feed pinned to its newest row. The
    /// bottom marker can disappear briefly when the keyboard/composer changes the
    /// viewport or a streaming row grows, neither of which is a user request to
    /// stop following.
    @State private var isFollowingLatest = true
    /// User drags opt out of follow mode while the follow-state reconciler
    /// resumes it once the live edge is visible and dragging has gone quiet.
    /// Corrective scrolls keep a following transcript pinned through late layout.
    @State private var isDraggingTranscript = false
    /// Tracks scroll intent without invalidating the view on every movement. The
    /// raw drag flag can remain set when ScrollView swallows the gesture's
    /// `onEnded`; the reconciler treats it as stale after a short interval.
    /// `sawLiveEdge` preserves that the user reached the bottom if streaming growth
    /// moves the marker away before a quiet-period reconciler gets to run.
    private final class DragActivity {
        var last = Date.distantPast
        var watchdogScheduled = false
        var sawLiveEdge = false
        var lastTopY = CGFloat.nan
    }
    @State private var dragActivity = DragActivity()
    /// Whether the transcript's bottom marker is inside the viewport. This is
    /// measured geometrically: rows live in an eager VStack, so onAppear/onDisappear
    /// describes mounting, not viewport visibility.
    @State private var isLatestVisible = true
    /// Current transcript viewport height. Keyboard and multiline-composer
    /// changes resize this even when the row data itself does not change.
    @State private var transcriptViewportHeight: CGFloat = 0
    /// Monotonic token used to coalesce the many scroll requests generated by a
    /// streaming turn into one post-layout jump, without overlapping animations.
    /// A reference box rather than view state: the revision `onChange` fires
    /// once per streamed event — often several per frame — and writing view
    /// state there trips "onChange action tried to update multiple times per
    /// frame".
    private final class ScrollToken { var value = 0 }
    @State private var scrollToken = ScrollToken()
    /// Draft text and pictures in the input bar. The picker/thumbnail
    /// affordances themselves live in `PictureComposer.swift`, shared with the
    /// new-session composer.
    @State private var draft = ""
    @State private var pictures: [DraftPicture] = []
    @State private var loadingPictures = false
    /// Pulsed true for one runloop turn right after a send. UIKit commits a
    /// pending autocorrection *after* the send action returns and writes the
    /// corrected string back into the binding, which is why a composer that was
    /// just cleared sometimes still shows the message that was sent. Turning
    /// autocorrection off for a beat makes UIKit discard that pending correction
    /// instead of committing it (see `send()`).
    @State private var suppressAutocorrect = false
    /// Whether the answer sheet is shown (decoupled from `pendingQuestion` so a
    /// swipe-dismiss can hide it while the pending gate persists — reopen via the
    /// banner).
    @State private var showQuestionSheet = false
    /// Whether the destructive stop confirmation is shown.
    @State private var showStopConfirm = false
    /// Whether the per-session settings sheet is shown.
    @State private var showSettings = false
    /// Presents the per-session usage sheet.
    @State private var showSessionUsage = false
    /// A commit to drill into via the diff viewer (set by tapping a commit row).
    @State private var commitTarget: CommitDiffTarget?

    private let client: YccClient
    private let project: String
    private let sessionID: String
    /// The display name carried in from the list, so the pushed screen is
    /// identifiable before (or without) any event arriving.
    private let title: String
    private static let bottomAnchor = "transcript-bottom"
    private static let transcriptCoordinateSpace = "transcript-scroll"
    private static let dragQuietPeriod: TimeInterval = 0.35
    private static let dragActivityStalePeriod: TimeInterval = 1.0
    init(client: YccClient, project: String = "", sessionID: String, live: Bool, title: String = "") {
        self.client = client
        self.project = project
        self.sessionID = sessionID
        _model = State(initialValue: SessionViewModel(
            source: client, project: project, sessionID: sessionID,
            mode: live ? .live : .persisted))
        let trimmed = title.trimmingCharacters(in: .whitespacesAndNewlines)
        self.title = trimmed.isEmpty
            ? (live ? "Live session" : "Session")
            : trimmed
    }

    var body: some View {
        ScrollViewReader { proxy in
            ZStack(alignment: .bottom) {
                transcript(proxy: proxy)
                if !isFollowingLatest {
                    jumpToLatestPill(proxy: proxy)
                        .padding(.bottom, 12)
                        .transition(.move(edge: .bottom).combined(with: .opacity))
                }
            }
            .animation(.default, value: isFollowingLatest)
            // A scalar revision avoids deep equality checks over every transcript
            // row (including the growing live-tail string) for each streamed delta.
            .onChange(of: model.transcriptRevision, initial: true) { _, _ in
                requestScrollToLatest(proxy: proxy)
            }
            .onChange(of: transcriptViewportHeight) { _, _ in
                requestScrollToLatest(proxy: proxy)
            }
            .onChange(of: composerFocused) { _, _ in
                requestScrollToLatest(proxy: proxy)
            }
        }
        .navigationTitle(title)
        .navigationBarTitleDisplayMode(.inline)
        // The transcript scrolls the full height of the screen, so without an
        // opaque bar its text bleeds through behind the status bar and title.
        .toolbarBackground(.visible, for: .navigationBar)
        .toolbar { titleToolbar }
        .toolbar { backlogShortcut }
        .toolbar { actionMenu }
        .navigationDestination(item: $commitTarget) { target in
            DiffView(
                title: "Commit \(target.shortSha)",
                content: .commit(project: project, sha: target.sha))
        }
        .safeAreaInset(edge: .bottom) { bottomChrome }
        // Manual keyboard avoidance (see KeyboardObserver): the automatic
        // keyboard safe area under a bottom `safeAreaInset` can get stuck after
        // sheet dismissals/navigation races (open SwiftUI bug, FB13296535),
        // stranding the input bar mid-screen with no keyboard beneath it. Opt
        // the whole screen out of the keyboard safe area and let `bottomChrome`
        // pad itself by the observed keyboard overlap instead.
        .ignoresSafeArea(.keyboard, edges: .bottom)
        .sheet(isPresented: $showSettings) {
            SessionSettingsView(
                client: client, sessionID: sessionID, coordinator: model.coordinatorModel)
        }
        .sheet(isPresented: $showSessionUsage) {
            SessionUsageSheet(
                client: client,
                project: project,
                sessionID: sessionID,
                currentContextTokensEstimate: model.currentContextTokensEstimate)
        }
        .sheet(isPresented: $showQuestionSheet) {
            if let pending = model.pendingQuestion {
                QuestionSheet(
                    pending: pending,
                    onAnswerSingle: { optionIndex, text in
                        if optionIndex >= 0 { await model.answer(optionIndex: optionIndex) }
                        else { await model.answer(text: text) }
                        noteAnswered()
                    },
                    onAnswerBatch: { answers in
                        await model.answerBatch(answers)
                        noteAnswered()
                    }
                )
                // Tie the sheet's identity to the gate: if `pendingQuestion`
                // changes shape while the sheet is open (e.g. a reopened session's
                // resumed agent asks a differently-sized batch), a new `rowID`
                // rebuilds QuestionSheet with correctly-sized @State instead of
                // reusing stale `texts`/`selected` arrays and trapping on an
                // out-of-range index.
                .id(pending.rowID)
            }
        }
        // Present/dismiss the sheet as the pending gate opens and clears — the
        // event stream is the source of truth (answering here or elsewhere emits
        // `question_answered`, which clears `pendingQuestion`).
        .onChange(of: model.pendingQuestion?.rowID) { _, rowID in
            showQuestionSheet = (rowID != nil)
        }
        .alert(
            "Action failed",
            isPresented: Binding(
                get: { model.actionError != nil },
                set: { if !$0 { model.actionError = nil } }
            ),
            presenting: model.actionError
        ) { _ in
            Button("OK", role: .cancel) { model.actionError = nil }
        } message: { message in
            Text(message)
        }
        .confirmationDialog(
            "Stop this session?",
            isPresented: $showStopConfirm,
            titleVisibility: .visible
        ) {
            Button("Stop session", role: .destructive) {
                Task { await model.stopSession() }
            }
            Button("Cancel", role: .cancel) {}
        } message: {
            Text("This hard-terminates the agent — there is no resume.")
        }
        .task { model.start() }
        .onDisappear {
            // Leaving the transcript is the moment the user has "read" it: record
            // the newest event they were shown, so later agent activity — a turn
            // that lands, or the session finishing while the phone is away —
            // shows up as unread on the list.
            markRead()
            model.stop()
        }
        .onChange(of: scenePhase) { _, phase in
            if phase == .active {
                model.reconnect()
            } else {
                // Backgrounding may be the last thing that happens to this view;
                // don't leave what is on screen counted as unread.
                markRead()
            }
        }
    }

    /// Record everything folded so far as seen for this session.
    private func markRead() {
        app.readMarks.markRead(
            sessionID: sessionID, through: model.lastEventTimestamp)
    }

    // MARK: - Bottom chrome (banner + input bar)

    @ViewBuilder
    private var bottomChrome: some View {
        VStack(spacing: 0) {
            if model.mode == .live {
                pendingQuestionBanner
                phaseBanner
            } else {
                banner(
                    "Reopen this session to continue the conversation",
                    systemImage: "clock.arrow.circlepath",
                    tint: .secondary
                )
            }
            inputBar
        }
        // Ride the keyboard by measured overlap (KeyboardObserver) rather than
        // the automatic keyboard safe area — see `.ignoresSafeArea(.keyboard)`
        // above. Padding sits *inside* the bar background so the material
        // covers the gap while the keyboard animates.
        .padding(.bottom, keyboard.overlap)
        .background(.bar)
    }

    /// When a question is pending but the sheet was swipe-dismissed, offer a way
    /// back in (the transcript row also still shows it as waiting).
    @ViewBuilder
    private var pendingQuestionBanner: some View {
        if model.pendingQuestion != nil, !showQuestionSheet {
            banner(
                "A question is waiting",
                systemImage: "questionmark.bubble.fill",
                tint: .orange,
                action: ("Answer", { showQuestionSheet = true })
            )
        }
    }

    @ViewBuilder
    private var phaseBanner: some View {
        switch model.phase {
        case .paused:
            banner(
                "Paused — send a steer or Resume",
                systemImage: "pause.circle.fill",
                tint: .orange,
                action: ("Resume", { Task { await model.resumeSession() } })
            )
        case .idle:
            banner("Session idle", systemImage: "moon.zzz.fill", tint: .secondary)
        case .error(let message, let retryable):
            let retryAction: (title: String, run: () -> Void)? =
                retryable ? ("Retry", { Task { await model.retry() } }) : nil
            banner(
                message.isEmpty ? "Session error" : "Error: \(message)",
                systemImage: "exclamationmark.triangle.fill",
                tint: .red,
                action: retryAction
            )
        case .stopped:
            banner("Session stopped", systemImage: "stop.circle.fill", tint: .secondary)
        case .running:
            EmptyView()
        }
    }

    private func banner(
        _ text: String,
        systemImage: String,
        tint: Color,
        action: (title: String, run: () -> Void)? = nil
    ) -> some View {
        HStack(spacing: 8) {
            Image(systemName: systemImage).foregroundStyle(tint)
            Text(text).font(.caption).foregroundStyle(.secondary)
            Spacer()
            if let action {
                Button(action.title, action: action.run)
                    .font(.caption.weight(.semibold))
                    .buttonStyle(.bordered)
                    .controlSize(.small)
            }
        }
        .padding(.horizontal, 12)
        .padding(.vertical, 6)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(tint.opacity(0.08))
    }

    private var inputBar: some View {
        VStack(alignment: .leading, spacing: 6) {
            PictureStrip(pictures: $pictures)
            HStack(spacing: 8) {
                PicturePickerButton(pictures: $pictures, isLoading: $loadingPictures) { message in
                    model.actionError = message
                }
                ComposerTextField(
                    placeholder: "Message…",
                    text: $draft,
                    focused: $composerFocused,
                    maxLines: 5,
                    autocorrectionDisabled: suppressAutocorrect,
                    onSubmit: send,
                    onPasteImages: { images in
                        pictures = PictureComposer.load(
                            pasted: images, current: pictures
                        ) { message in
                            model.actionError = message
                        }
                    }
                )
                Button(action: send) {
                    Image(systemName: "arrow.up.circle.fill")
                        .font(.title2)
                }
                .disabled(
                    loadingPictures ||
                    (draft.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty && pictures.isEmpty)
                )
            }
        }
        .padding(.horizontal, 12)
        .padding(.vertical, 8)
    }

    private func send() {
        let text = draft
        let images = pictures.map(\.image)
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty || !images.isEmpty else { return }
        draft = ""
        pictures = []
        // Clearing the binding is not enough on its own: if the keyboard still
        // holds an uncommitted autocorrection (the user tapped send without
        // accepting or dismissing the suggestion), UIKit commits it *after* this
        // action and writes the corrected text straight back into the freshly
        // emptied field — the message goes out but the composer keeps showing it.
        // Dropping autocorrection for one runloop turn makes UIKit throw that
        // pending correction away, and the deferred re-clear mops up any
        // write-back that still lands before the pulse takes effect.
        suppressAutocorrect = true
        Task { @MainActor in
            draft = ""
            suppressAutocorrect = false
        }
        Task { await model.send(text: text, images: images) }
    }

    /// Tell the rest of the app this session's question is dealt with, so the
    /// inbox and drawer badges stop nagging before the next list refresh.
    /// Harmless if the answer failed — the next refresh restores the truth.
    @MainActor
    private func noteAnswered() {
        app.noteQuestionAnswered(sessionID: sessionID)
    }

    private func transcript(proxy: ScrollViewProxy) -> some View {
        ScrollView {
            // Keep transcript rows eagerly mounted. A LazyVStack can lose its
            // estimated content geometry when the last row changes height many
            // times per second (the streaming tail) while ScrollViewReader also
            // keeps that row pinned. The resulting stale offset presents as an
            // empty transcript until a manual scroll forces another layout pass.
            // Session rows already collapse heavy tool/thinking details, so the
            // predictable geometry is worth the modest eager-layout cost here.
            VStack(alignment: .leading, spacing: 10) {
                if model.durableRows.isEmpty, model.liveTails.isEmpty, model.state == .loading {
                    ProgressView().frame(maxWidth: .infinity).padding(.top, 40)
                }
                // Keep immutable history separate from rapidly-changing tails.
                // Building one combined array every 100ms made SwiftUI diff the
                // entire transcript for every snapshot.
                ForEach(model.durableRows) { row in
                    TranscriptRowView(
                        row: row,
                        onOpenCommit: { sha in
                            commitTarget = CommitDiffTarget(sha: sha)
                        },
                        loadPicture: { attachmentID in
                            guard !attachmentID.isEmpty,
                                  let image = try? await client.getSessionAttachment(
                                    project: project,
                                    sessionId: sessionID,
                                    attachmentId: attachmentID
                                  ) else { return nil }
                            return image.data
                        }
                    )
                    .equatable()
                    .id(row.id)
                }
                ForEach(model.liveTails) { liveTail in
                    // Each actor owns a stable subtree. Equatable rendering lets
                    // one subagent append without re-running the unchanged tails;
                    // the changed row still receives every snapshot for TextKit.
                    TranscriptRowView(row: liveTail, model: model.coordinatorModel)
                        .equatable()
                        .id(liveTail.id)
                }
                if model.liveTails.isEmpty, model.isAwaitingAgentActivity {
                    workingRow
                        .id("agent-working")
                }
                // A small marker row tells us geometrically when the latest
                // content is visible. With this eager VStack the marker remains
                // mounted while offscreen, so lifecycle callbacks cannot answer
                // that question reliably.
                Color.clear
                    .frame(height: 1)
                    .id(Self.bottomAnchor)
                    .background {
                        GeometryReader { geometry in
                            Color.clear.preference(
                                key: TranscriptBottomPreferenceKey.self,
                                value: geometry.frame(
                                    in: .named(Self.transcriptCoordinateSpace)).maxY)
                        }
                    }
            }
            .padding()
            // Content growth below leaves this top edge fixed while unpinned;
            // user scrolling changes it. That lets the reconciler distinguish a
            // deliberate scroll away from streaming layout growth.
            .background {
                GeometryReader { geometry in
                    Color.clear.preference(
                        key: TranscriptTopPreferenceKey.self,
                        value: geometry.frame(
                            in: .named(Self.transcriptCoordinateSpace)).minY)
                }
            }
        }
        .coordinateSpace(name: Self.transcriptCoordinateSpace)
        .onPreferenceChange(TranscriptBottomPreferenceKey.self) { bottomY in
            let tolerance: CGFloat = 8
            let now = Date()
            let dragAge = now.timeIntervalSince(dragActivity.last)
            // Only a currently active raw drag may stop follow here, so content
            // growth after release cannot masquerade as user scrollback. Bound the
            // flag by recency in case ScrollView swallows `onEnded`; the top-edge
            // handler intentionally uses recency alone to include deceleration.
            let dragging = isDraggingTranscript && dragAge < Self.dragActivityStalePeriod
            isLatestVisible = bottomY <= transcriptViewportHeight + tolerance
            if isLatestVisible {
                // Preserve that the user reached the live edge even if streaming
                // growth moves it away before drag reconciliation goes quiet.
                dragActivity.sawLiveEdge = true
            }
            // Only a recent user drag can opt out of follow mode. Content growth
            // while pinned can briefly move the marker below the viewport before
            // the explicit scroll request settles, and must not look like scrollback.
            if dragging, !isLatestVisible {
                stopFollowingLatest()
            } else if isLatestVisible || dragActivity.sawLiveEdge,
                      !isFollowingLatest, !dragging,
                      dragAge >= Self.dragQuietPeriod {
                // Reaching the live edge by scrolling is equivalent to tapping the
                // pill. If growth moved it again, restore the pin immediately.
                isFollowingLatest = true
                if !isLatestVisible {
                    requestScrollToLatest(proxy: proxy)
                }
            } else if !isLatestVisible, isFollowingLatest, !dragging {
                // A scroll can land before late text or keyboard layout finishes.
                // Coalesce a corrective non-animated pin rather than waiting for
                // the next transcript event to trigger another request.
                requestScrollToLatest(proxy: proxy)
            }
        }
        .onPreferenceChange(TranscriptTopPreferenceKey.self) { topY in
            let previousTopY = dragActivity.lastTopY
            let moved = !previousTopY.isNaN && abs(topY - previousTopY) > 0.5
            dragActivity.lastTopY = topY
            let dragAge = Date().timeIntervalSince(dragActivity.last)
            let dragging = dragAge < Self.dragActivityStalePeriod
            // Offset movement during a recent drag is user scrolling; unlike pure
            // growth below, it revokes a previously observed live-edge intent.
            if moved, dragging, !isLatestVisible {
                dragActivity.sawLiveEdge = false
            }
        }
        .simultaneousGesture(
            DragGesture(minimumDistance: 4)
                .onChanged { value in
                    dragActivity.last = Date()
                    // Schedule from activity, not onEnded: ScrollView can swallow
                    // onEnded, and an idle transcript may produce no later geometry
                    // preference change to clear the wedged drag state.
                    if !dragActivity.watchdogScheduled {
                        dragActivity.watchdogScheduled = true
                        Task { @MainActor in
                            defer { dragActivity.watchdogScheduled = false }
                            while true {
                                let elapsed = Date().timeIntervalSince(dragActivity.last)
                                guard elapsed < Self.dragActivityStalePeriod else { break }
                                let remaining = Self.dragActivityStalePeriod - elapsed
                                do {
                                    try await Task.sleep(
                                        nanoseconds: UInt64(remaining * 1_000_000_000))
                                } catch {
                                    return
                                }
                            }
                            isDraggingTranscript = false
                            if isLatestVisible || dragActivity.sawLiveEdge,
                               !isFollowingLatest {
                                isFollowingLatest = true
                                if !isLatestVisible {
                                    requestScrollToLatest(proxy: proxy)
                                }
                            }
                        }
                    }
                    if !isDraggingTranscript { isDraggingTranscript = true }
                    // At gesture recognition time the geometry preference can lag
                    // the finger by one layout pass. A downward swipe is explicitly
                    // toward older content, so it must win even before that pass.
                    if !isLatestVisible || value.translation.height > 0 {
                        dragActivity.sawLiveEdge = false
                        stopFollowingLatest()
                    }
                }
                .onEnded { value in
                    // Deceleration continues after this callback. Follow mode was
                    // already disabled as soon as the drag moved off the live edge.
                    isDraggingTranscript = false
                    dragActivity.last = Date()
                    // Even if the marker is or recently was within tolerance at
                    // release, do not re-pin against a downward fling toward older
                    // content.
                    if value.predictedEndTranslation.height <= 0,
                       isLatestVisible || dragActivity.sawLiveEdge,
                       !isFollowingLatest {
                        isFollowingLatest = true
                        requestScrollToLatest(proxy: proxy)
                    }
                    // Rubber-band and deceleration can settle at the live edge after
                    // the last geometry preference change. Reconcile once more after
                    // they have gone quiet so an idle transcript can resume too.
                    Task { @MainActor in
                        try? await Task.sleep(nanoseconds: 450_000_000)
                        guard !isFollowingLatest,
                              isLatestVisible || dragActivity.sawLiveEdge,
                              !isDraggingTranscript else { return }
                        isFollowingLatest = true
                        if !isLatestVisible {
                            requestScrollToLatest(proxy: proxy)
                        }
                    }
                }
        )
        .background {
            GeometryReader { geometry in
                Color.clear
                    .onAppear { transcriptViewportHeight = geometry.size.height }
                    .onChange(of: geometry.size.height) { _, height in
                        transcriptViewportHeight = height
                    }
            }
        }
        // Do not use `.defaultScrollAnchor(.bottom)` here. SwiftUI also consults
        // that anchor on content-size changes, which moves the viewport whenever
        // the live tail grows even while the user is reading scrollback. Initial
        // and subsequent live-edge positioning are both handled explicitly by
        // `requestScrollToLatest` while follow mode is enabled.
    }

    /// Immediate acknowledgement after StartSession/SendInput, shown until the
    /// event stream produces the first meaningful piece of agent activity. Names
    /// the model when the log has told us which one is working.
    private var workingRow: some View {
        HStack(spacing: 10) {
            ProgressView()
                .controlSize(.small)
            Text(workingLabel)
                .font(.subheadline)
                .foregroundStyle(.secondary)
        }
        .padding(.horizontal, 12)
        .padding(.vertical, 10)
        .background(Color(.secondarySystemBackground), in: RoundedRectangle(cornerRadius: 14))
        .frame(maxWidth: .infinity, alignment: .leading)
        .accessibilityElement(children: .combine)
        .accessibilityLabel(workingLabel)
    }

    private var workingLabel: String {
        model.coordinatorModel.isEmpty
            ? "Agent is working…"
            : "\(model.coordinatorModel) is working…"
    }

    private func stopFollowingLatest() {
        guard isFollowingLatest else { return }
        isFollowingLatest = false
        // Invalidate a post-layout or keyboard-settle request that was queued
        // while the transcript was still following the live edge.
        scrollToken.value &+= 1
    }

    private func requestScrollToLatest(proxy: ScrollViewProxy) {
        guard isFollowingLatest else { return }
        scrollToken.value &+= 1
        let request = scrollToken.value
        Task { @MainActor in
            // Let LazyVStack, the keyboard safe area, and the composer all
            // finish the current layout pass. A newer request supersedes us.
            await Task.yield()
            guard request == scrollToken.value, isFollowingLatest else { return }
            proxy.scrollTo(Self.bottomAnchor, anchor: .bottom)
            // Keyboard presentation is animated over several layout passes;
            // settle once more after it reaches its final safe-area height.
            if composerFocused {
                try? await Task.sleep(nanoseconds: 300_000_000)
                guard request == scrollToken.value, isFollowingLatest else { return }
                proxy.scrollTo(Self.bottomAnchor, anchor: .bottom)
            }
        }
    }

    private func jumpToLatestPill(proxy: ScrollViewProxy) -> some View {
        Button {
            isFollowingLatest = true
            proxy.scrollTo(Self.bottomAnchor, anchor: .bottom)
        } label: {
            Label("Jump to latest", systemImage: "arrow.down")
                .font(.subheadline.weight(.semibold))
                .padding(.horizontal, 14)
                .padding(.vertical, 8)
                .background(.thinMaterial, in: Capsule())
                .overlay(Capsule().strokeBorder(.quaternary))
        }
        .buttonStyle(.plain)
    }

    /// A two-line inline title: the session's name over its project and live
    /// state. An inline `navigationTitle` alone can only show one line, and
    /// "which project is this?" is the question a cross-project feed makes
    /// constant. Folding the connection state in here also frees a toolbar slot
    /// for the backlog shortcut.
    @ToolbarContentBuilder
    private var titleToolbar: some ToolbarContent {
        ToolbarItem(placement: .principal) {
            VStack(spacing: 0) {
                Text(title)
                    .font(.headline)
                    .lineLimit(1)
                    // Tail, not middle: these titles are derived from the
                    // opening prompt, so the front of the string is the part
                    // that identifies the session.
                    .truncationMode(.tail)
