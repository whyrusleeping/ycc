/// Renders a single ``TranscriptRow``. Bubbles for messages; collapsed,
/// tappable disclosure rows for thinking and tool calls; compact system rows.
private struct TranscriptRowView: View, Equatable {
    let row: TranscriptRow
    /// The logical model currently producing turns, shown beside the coordinator's
    /// streaming indicator. Only supplied for live tails; durable rows leave it
    /// empty. It participates in ``==`` so a role change refreshes the label.
    var model: String = ""
    /// Called with the commit sha when a `commit_made` row is tapped.
    var onOpenCommit: (String) -> Void = { _ in }
    /// Lazily retrieves a retained user picture. Returning nil renders the
    /// metadata fallback instead of a broken thumbnail.
    var loadPicture: @Sendable (String) async -> Data? = { _ in nil }

    /// The callbacks are stable for a transcript row's lifetime; row payload and
    /// the optional live model label are the only inputs that should invalidate
    /// its subtree. This keeps old MarkdownText rows from being reparsed whenever
    /// a live tail changes.
    static func == (lhs: Self, rhs: Self) -> Bool {
        lhs.row == rhs.row && lhs.model == rhs.model
    }

    var body: some View {
        if row.actorEmoji.isEmpty {
            rowContent
        } else {
            VStack(alignment: .leading, spacing: 4) {
                Text("\(row.actorEmoji) \(row.actor)")
                    .font(.caption2.weight(.medium))
                    .foregroundStyle(.secondary)
                    .accessibilityLabel("Subagent \(row.actor)")
                rowContent
            }
            .frame(maxWidth: .infinity, alignment: .leading)
        }
    }

    @ViewBuilder
    private var rowContent: some View {
        switch row.kind {
        case .userMessage(let text, let pictures):
            userBubble(text: text, pictures: pictures)
        case .modelMessage(let text):
            // The plant prefix already carries the subagent label; coordinator
            // rows retain the existing textual actor heading inside the bubble.
            bubble(text: text, isUser: false, actor: row.actorEmoji.isEmpty ? row.actor : "")
        case .finalReport(let text):
            finalReport(text)
        case .thinking(let text):
            ExpandableRow(
                title: "Thinking",
                systemImage: "brain",
                tint: .purple,
                preview: ToolPreview.oneLine(text, limit: 70),
                detail: text,
                detailIsAside: true
            )
        case .tool(let name, let status, let args, let output):
            ToolRowView(name: name, status: status, args: args, output: output)
        case .question(let prompt, let options, let answer):
            QuestionRowView(prompt: prompt, options: options, answer: answer)
        case .system(let text):
            systemRow(text)
        case .commit(let text, let sha):
            commitRow(text, sha: sha)
        case .liveTail(let text):
            liveTail(
                text,
                append: row.liveAppend,
                appendBaseUTF8: row.liveAppendBaseUTF8
            )
        }
    }

    private func userBubble(text: String, pictures: [TranscriptRow.Picture]) -> some View {
        HStack {
            Spacer(minLength: 40)
            VStack(alignment: .trailing, spacing: 8) {
                if !pictures.isEmpty {
                    LazyVGrid(
                        columns: pictures.count == 1
                            ? [GridItem(.flexible())]
                            : [GridItem(.flexible()), GridItem(.flexible())],
                        spacing: 6
                    ) {
                        ForEach(Array(pictures.enumerated()), id: \.offset) { _, picture in
                            TranscriptPicture(picture: picture, loadPicture: loadPicture)
                        }
                    }
                    .frame(maxWidth: pictures.count == 1 ? 260 : 300)
                }
                if !text.isEmpty {
                    Text(text)
                        .textSelection(.enabled)
                        .padding(.horizontal, 12)
                        .padding(.vertical, 8)
                        .background(Color.accentColor.opacity(0.85), in: RoundedRectangle(cornerRadius: 14))
                        .foregroundStyle(.white)
                }
            }
        }
    }

    private func bubble(text: String, isUser: Bool, actor: String = "") -> some View {
        HStack {
            if isUser { Spacer(minLength: 40) }
            VStack(alignment: isUser ? .trailing : .leading, spacing: 2) {
                if !isUser, !actor.isEmpty {
                    Text(actor).font(.caption2).foregroundStyle(.secondary)
                }
                Group {
                    if isUser {
                        // User messages stay plain text — they were typed, not
                        // authored in markdown.
                        Text(text.isEmpty ? " " : text)
                    } else {
                        // Agent messages render as markdown (headings, lists,
                        // inline styles, fenced code blocks).
                        MarkdownText(text: text.isEmpty ? " " : text)
                    }
                }
                .textSelection(.enabled)
                .padding(.horizontal, 12)
                .padding(.vertical, 8)
                .background(
                    isUser ? Color.accentColor.opacity(0.85) : Color(.secondarySystemBackground),
                    in: RoundedRectangle(cornerRadius: 14)
                )
                .foregroundStyle(isUser ? .white : .primary)
            }
            if !isUser { Spacer(minLength: 40) }
        }
    }

    /// The finish message is the primary result of a session, not a lifecycle
    /// footnote: keep it always expanded, render its Markdown structure, and give
    /// it a distinct success card that remains easy to find in a long transcript.
    private func finalReport(_ text: String) -> some View {
        VStack(alignment: .leading, spacing: 10) {
            Label("Finished", systemImage: "checkmark.circle.fill")
                .font(.headline)
                .foregroundStyle(.green)
            MarkdownText(text: text)
                .textSelection(.enabled)
                .frame(maxWidth: .infinity, alignment: .leading)
        }
        .padding(14)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(Color.green.opacity(0.09), in: RoundedRectangle(cornerRadius: 14))
        .overlay {
            RoundedRectangle(cornerRadius: 14)
                .stroke(Color.green.opacity(0.28), lineWidth: 1)
        }
        .accessibilityElement(children: .contain)
        .accessibilityLabel("Session finished")
    }

    private func systemRow(_ text: String) -> some View {
        HStack(spacing: 6) {
            Image(systemName: "circle.fill").font(.system(size: 4)).foregroundStyle(.tertiary)
            Text(text)
                .font(.caption)
                .foregroundStyle(.secondary)
                .frame(maxWidth: .infinity, alignment: .leading)
        }
    }

    /// A commit row: like a system row, but tappable to drill into the commit's
    /// diff when a sha is present. Without a sha it degrades to a plain row.
    @ViewBuilder
    private func commitRow(_ text: String, sha: String) -> some View {
        if sha.isEmpty {
            systemRow(text)
        } else {
            Button {
                onOpenCommit(sha)
            } label: {
                HStack(spacing: 6) {
                    Image(systemName: "arrow.triangle.branch")
                        .font(.caption2)
                        .foregroundStyle(.blue)
                    Text(text)
                        .font(.caption)
                        .foregroundStyle(.secondary)
                        .frame(maxWidth: .infinity, alignment: .leading)
                    Image(systemName: "chevron.right")
                        .font(.caption2)
                        .foregroundStyle(.tertiary)
                }
            }
            .buttonStyle(.plain)
        }
    }

    private var streamingLabel: String {
        if !row.actorEmoji.isEmpty { return "streaming" }
        let actor = row.actor.trimmingCharacters(in: .whitespacesAndNewlines)
        if !actor.isEmpty, actor != "coordinator" {
            return "\(actor) · streaming"
        }
        return model.isEmpty ? "streaming" : "\(model) · streaming"
    }

    private func liveTail(
        _ text: String,
        append: String?,
        appendBaseUTF8: Int?
    ) -> some View {
        HStack {
            VStack(alignment: .leading, spacing: 2) {
                HStack(spacing: 4) {
                    ProgressView().scaleEffect(0.6)
                    Text(streamingLabel)
                        .font(.caption2).foregroundStyle(.secondary)
                }
                // Unlike SwiftUI.Text, this keeps one TextKit storage/layout tree
                // alive and appends the new suffix for ordinary growing snapshots.
                // Replacing an ever-longer Text at 10 Hz repeatedly shaped and laid
                // out the full response, producing quadratic-feeling slowdown.
                IncrementalStreamingText(
                    text: text,
                    append: append,
                    appendBaseUTF8: appendBaseUTF8
                )
                .padding(.horizontal, 12)
                    .padding(.vertical, 8)
                    .background(Color(.secondarySystemBackground), in: RoundedRectangle(cornerRadius: 14))
                    .foregroundStyle(.primary)
            }
            Spacer(minLength: 40)
        }
    }
}

/// One lazily-loaded picture inside a user transcript row. The placeholder is
/// intentionally durable: old logs and reclaimed payloads still communicate
/// that the original message contained a picture.
private struct TranscriptPicture: View {
    let picture: TranscriptRow.Picture
    let loadPicture: @Sendable (String) async -> Data?
    @State private var data: Data?
    @State private var finishedLoading = false

    var body: some View {
        Group {
            if let data, let image = UIImage(data: data) {
                Image(uiImage: image)
                    .resizable()
                    .scaledToFit()
                    .frame(maxHeight: 280)
            } else {
                VStack(spacing: 6) {
                    if !finishedLoading && !picture.attachmentID.isEmpty {
                        ProgressView()
                    } else {
                        Image(systemName: "photo")
                            .font(.title2)
                    }
                    Text("Picture attached")
                        .font(.caption)
                    if !picture.filename.isEmpty {
                        Text(picture.filename)
                            .font(.caption2)
                            .lineLimit(1)
                    }
                }
                .foregroundStyle(.secondary)
                .frame(maxWidth: .infinity, minHeight: 100)
            }
        }
        .padding(4)
        .background(Color(.secondarySystemBackground), in: RoundedRectangle(cornerRadius: 14))
        .clipShape(RoundedRectangle(cornerRadius: 14))
        .task(id: picture.attachmentID) {
            guard !picture.attachmentID.isEmpty else {
                finishedLoading = true
                return
            }
            data = await loadPicture(picture.attachmentID)
            finishedLoading = true
        }
        .accessibilityLabel(picture.filename.isEmpty ? "Picture attached" : "Picture attached, \(picture.filename)")
    }
}

/// A non-scrolling, selectable TextKit view optimized for snapshot-style model
/// output. Normal snapshots extend the previous text, so mutate NSTextStorage by
/// only the suffix and let TextKit incrementally lay out the addition. A retry or
/// other non-prefix replacement falls back to replacing the complete value.
private struct IncrementalStreamingText: UIViewRepresentable {
    let text: String
    let append: String?
    let appendBaseUTF8: Int?

    final class Coordinator {
        var renderedText = ""
        var renderedUTF8Count = 0
        var font: UIFont?
    }

    func makeCoordinator() -> Coordinator { Coordinator() }

    func makeUIView(context: Context) -> UITextView {
        let view = UITextView()
        view.backgroundColor = .clear
        view.isEditable = false
        view.isSelectable = true
        view.isScrollEnabled = false
        view.textContainerInset = .zero
        view.textContainer.lineFragmentPadding = 0
        view.setContentCompressionResistancePriority(.defaultLow, for: .horizontal)
        view.setContentHuggingPriority(.required, for: .vertical)
        return view
    }

    func updateUIView(_ view: UITextView, context: Context) {
        let font = UIFont.preferredFont(forTextStyle: .body)
        let foreground = UIColor.label
        let attributes: [NSAttributedString.Key: Any] = [
            .font: font,
            .foregroundColor: foreground,
        ]
        let coordinator = context.coordinator
        var nextUTF8Count = coordinator.renderedUTF8Count

        if coordinator.font != font {
            // Dynamic Type/style changes are rare and legitimately require a
            // complete relayout; streamed snapshots normally stay on append path.
            view.attributedText = NSAttributedString(string: text, attributes: attributes)
            nextUTF8Count = text.utf8.count
        } else if let append,
                  let appendBaseUTF8,
                  appendBaseUTF8 == coordinator.renderedUTF8Count {
            // Fast path from a daemon-provided verified base offset: no growing
            // prefix/count scan and no reconstruction of the accumulated string.
            if !append.isEmpty {
                view.textStorage.append(NSAttributedString(string: append, attributes: attributes))
            }
            nextUTF8Count = appendBaseUTF8 + append.utf8.count
        } else if text.hasPrefix(coordinator.renderedText) {
            // Compatibility path for older daemons that only send snapshots.
            let suffix = text.dropFirst(coordinator.renderedText.count)
            if !suffix.isEmpty {
                view.textStorage.append(NSAttributedString(string: String(suffix), attributes: attributes))
            }
            nextUTF8Count = text.utf8.count
        } else if text != coordinator.renderedText {
            // Retry/reset, lossy hint gap, or another non-prefix replacement.
            view.attributedText = NSAttributedString(string: text, attributes: attributes)
            nextUTF8Count = text.utf8.count
        }

        coordinator.renderedText = text
        coordinator.renderedUTF8Count = nextUTF8Count
        coordinator.font = font
    }

    func sizeThatFits(
        _ proposal: ProposedViewSize,
        uiView: UITextView,
        context: Context
    ) -> CGSize? {
        guard let width = proposal.width else { return nil }
        let fitted = uiView.sizeThatFits(
            CGSize(width: width, height: .greatestFiniteMagnitude))
        return CGSize(width: width, height: fitted.height)
    }
}

/// A collapsed one-liner that expands to reveal detail text on tap.
