/// The answer sheet for a pending `ask_user` gate. A single question offers its
/// suggested options as buttons plus a free-text field (`AnswerQuestion`). A
/// batch renders one section per question and submits positionally
/// (`AnswerQuestions`, `answers[i]`). The sheet auto-dismisses when the gate
/// clears (answered here or from another client) via the parent's `onChange`.
private struct QuestionSheet: View {
    let pending: SessionProjection.PendingQuestion
    /// (optionIndex, text): optionIndex >= 0 selects an option, -1 sends text.
    let onAnswerSingle: (Int, String) async -> Void
    /// Positional batch answers.
    let onAnswerBatch: ([(text: String, optionIndex: Int)]) async -> Void

    @Environment(\.dismiss) private var dismiss
    /// Per-question free-text drafts.
    @State private var texts: [String]
    /// Per-question selected option index (-1 = none).
    @State private var selected: [Int]

    init(
        pending: SessionProjection.PendingQuestion,
        onAnswerSingle: @escaping (Int, String) async -> Void,
        onAnswerBatch: @escaping ([(text: String, optionIndex: Int)]) async -> Void
    ) {
        self.pending = pending
        self.onAnswerSingle = onAnswerSingle
        self.onAnswerBatch = onAnswerBatch
        _texts = State(initialValue: Array(repeating: "", count: pending.questions.count))
        _selected = State(initialValue: Array(repeating: -1, count: pending.questions.count))
    }

    var body: some View {
        NavigationStack {
            Form {
                ForEach(Array(pending.questions.enumerated()), id: \.offset) { index, question in
                    Section {
                        // The question is the point of this sheet: render it as
                        // full-size prose, not a small-caps section header that
                        // truncates a multi-sentence, self-contained ask.
                        VStack(alignment: .leading, spacing: 4) {
                            if pending.isBatch {
                                Text("Question \(index + 1) of \(pending.questions.count)")
                                    .font(.caption2.weight(.semibold))
                                    .foregroundStyle(.secondary)
                            }
                            MarkdownText(text: question.prompt)
                                .font(.callout)
                        }
                        .padding(.vertical, 2)
                        .listRowBackground(Color.clear)

                        ForEach(Array(question.options.enumerated()), id: \.offset) { optIdx, option in
                            optionRow(index: index, optIdx: optIdx, option: option)
                        }
                        TextField(
                            question.options.isEmpty ? "Type an answer…" : "Or type your own…",
                            text: binding(index), axis: .vertical)
                            .lineLimit(1...4)
                            .onChange(of: text(at: index)) { _, newValue in
                                // Typing overrides a picked option.
                                if !newValue.isEmpty { setSelected(-1, at: index) }
                            }
                        if !pending.isBatch {
                            singleSendSection
                        }
                    }
                }
            }
            .navigationTitle(pending.isBatch ? "Answer questions" : "The agent is asking")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .cancellationAction) {
                    Button("Cancel") { dismiss() }
                }
                if pending.isBatch {
                    ToolbarItem(placement: .confirmationAction) {
                        Button("Submit") { submitBatch() }
                            .disabled(!allAnswered)
                    }
                }
            }
        }
    }

    private func optionRow(index: Int, optIdx: Int, option: String) -> some View {
        Button {
            if pending.isBatch {
                setSelected(optIdx, at: index)
                setText("", at: index)
            } else {
                // Single question: an option tap answers immediately.
                Task {
                    await onAnswerSingle(optIdx, "")
                    dismiss()
                }
            }
        } label: {
            HStack(spacing: 10) {
                Image(systemName: selectedValue(at: index) == optIdx
                    ? "largecircle.fill.circle" : "circle")
                    .foregroundStyle(selectedValue(at: index) == optIdx ? Color.accentColor : .secondary)
                Text(option)
                    .foregroundStyle(.primary)
                    .multilineTextAlignment(.leading)
                Spacer(minLength: 0)
            }
        }
    }

    // Bounds-safe accessors for the per-question `@State` arrays. These arrays
    // are seeded to `pending.questions.count` in `init` and the `.id(rowID)` on
    // the sheet rebuilds this view when the gate changes, but guarding here means
    // a transient shape desync can never trap on an out-of-range subscript.
    private func text(at index: Int) -> String {
        texts.indices.contains(index) ? texts[index] : ""
    }

    private func setText(_ value: String, at index: Int) {
        guard texts.indices.contains(index) else { return }
        texts[index] = value
    }

    private func selectedValue(at index: Int) -> Int {
        selected.indices.contains(index) ? selected[index] : -1
    }

    private func setSelected(_ value: Int, at index: Int) {
        guard selected.indices.contains(index) else { return }
        selected[index] = value
    }

    /// A binding to a per-question text draft, with a trailing send button for
    /// the single-question case.
    private func binding(_ index: Int) -> Binding<String> {
        Binding(get: { text(at: index) }, set: { setText($0, at: index) })
    }

    /// For a single question, provide an inline send action for free text.
    private var singleSendSection: some View {
        Button("Send") {
            Task {
                await onAnswerSingle(-1, text(at: 0))
                dismiss()
            }
        }
        .disabled(text(at: 0).trimmingCharacters(in: .whitespacesAndNewlines).isEmpty)
    }

    private var allAnswered: Bool {
        for i in pending.questions.indices {
            let hasText = !text(at: i).trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
            if selectedValue(at: i) < 0 && !hasText { return false }
        }
        return true
    }

    private func submitBatch() {
        let answers: [(text: String, optionIndex: Int)] = pending.questions.indices.map { i in
            let sel = selectedValue(at: i)
            if sel >= 0 { return (text: "", optionIndex: sel) }
            return (text: text(at: i), optionIndex: -1)
        }
        Task {
            await onAnswerBatch(answers)
            dismiss()
        }
    }
}

