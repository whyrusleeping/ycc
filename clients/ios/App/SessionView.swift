import PhotosUI
import SwiftUI
import UIKit
import YccKit

/// Read-only-plus-interactive session transcript feed — the projection of the
/// event log (docs/design/ios-client.md §6 phase 1 steps 3–4). Live sessions
/// stream via `Subscribe`; persisted sessions load once via
/// `GetSessionTranscript`. The heavy lifting (folding, reconnect, actions) lives
/// in ``SessionViewModel``; this view is a thin renderer.
///
/// Interactions (task 0183): a sticky input bar (`SendInput`), an answer sheet
/// for `ask_user` (`AnswerQuestion`/`AnswerQuestions`), and an overflow menu for
/// interrupt/resume/stop. Chrome (banners) reflects the derived session phase.
struct SessionView: View {
    @Environment(AppModel.self) private var app
    @Environment(\.scenePhase) private var scenePhase

    @State private var model: SessionViewModel
    @FocusState private var composerFocused: Bool
    /// Whether new content should keep the feed pinned to its newest row. The
    /// bottom marker can disappear briefly when the keyboard/composer changes the
    /// viewport or a streaming row grows, neither of which is a user request to
    /// stop following.
    @State private var isFollowingLatest = true
    /// Suppresses marker-driven re-follow while the user is actively scrolling.
    @State private var isDraggingTranscript = false
    /// Whether the transcript's bottom marker is inside the viewport. This is
    /// measured geometrically: rows live in an eager VStack, so onAppear/onDisappear
    /// describes mounting, not viewport visibility.
    @State private var isLatestVisible = true
    /// Current transcript viewport height. Keyboard and multiline-composer
    /// changes resize this even when the row data itself does not change.
    @State private var transcriptViewportHeight: CGFloat = 0
    /// Monotonic token used to coalesce the many scroll requests generated by a
    /// streaming turn into one post-layout jump, without overlapping animations.
    /// A reference box rather than view state: the revision `onChange` fires
    /// once per streamed event — often several per frame — and writing view
    /// state there trips "onChange action tried to update multiple times per
    /// frame".
    private final class ScrollToken { var value = 0 }
    @State private var scrollToken = ScrollToken()
    /// Draft text and pictures in the input bar.
    @State private var draft = ""
    @State private var photoItems: [PhotosPickerItem] = []
    @State private var pictures: [DraftPicture] = []
    @State private var loadingPictures = false
    /// Whether the answer sheet is shown (decoupled from `pendingQuestion` so a
    /// swipe-dismiss can hide it while the pending gate persists — reopen via the
    /// banner).
    @State private var showQuestionSheet = false
    /// Whether the destructive stop confirmation is shown.
    @State private var showStopConfirm = false
    /// Whether the per-session settings sheet is shown.
    @State private var showSettings = false
    /// A commit to drill into via the diff viewer (set by tapping a commit row).
    @State private var commitTarget: CommitDiffTarget?

    private let client: YccClient
    private let project: String
    private let sessionID: String
    /// The display name carried in from the list, so the pushed screen is
    /// identifiable before (or without) any event arriving.
    private let title: String
    private static let bottomAnchor = "transcript-bottom"
    private static let transcriptCoordinateSpace = "transcript-scroll"
    /// Mirrors the daemon's per-message cap (spec §12); the merge/capacity
    /// rules themselves live in `PictureAttachments` so they are unit-tested.
    private static let maxPictures = PictureAttachments.maxCount
    private static let maxPictureBytes = 5 * 1_024 * 1_024

    private struct DraftPicture: Identifiable {
        let id = UUID()
        let image: MessageImage
        let preview: UIImage
    }

    init(client: YccClient, project: String = "", sessionID: String, live: Bool, title: String = "") {
        self.client = client
        self.project = project
        self.sessionID = sessionID
        _model = State(initialValue: SessionViewModel(
            source: client, project: project, sessionID: sessionID,
            mode: live ? .live : .persisted))
        let trimmed = title.trimmingCharacters(in: .whitespacesAndNewlines)
        self.title = trimmed.isEmpty
            ? (live ? "Live session" : "Session")
            : trimmed
    }

    var body: some View {
        ScrollViewReader { proxy in
            ZStack(alignment: .bottom) {
                transcript
                if !isFollowingLatest {
                    jumpToLatestPill(proxy: proxy)
                        .padding(.bottom, 12)
                        .transition(.move(edge: .bottom).combined(with: .opacity))
                }
            }
            .animation(.default, value: isFollowingLatest)
            // A scalar revision avoids deep equality checks over every transcript
            // row (including the growing live-tail string) for each streamed delta.
            .onChange(of: model.transcriptRevision, initial: true) { _, _ in
                requestScrollToLatest(proxy: proxy)
            }
            .onChange(of: transcriptViewportHeight) { _, _ in
                requestScrollToLatest(proxy: proxy)
            }
            .onChange(of: composerFocused) { _, _ in
                requestScrollToLatest(proxy: proxy)
            }
        }
        .navigationTitle(title)
        .navigationBarTitleDisplayMode(.inline)
        .toolbar { titleToolbar }
        .toolbar { statusToolbar }
        .toolbar { if model.mode == .live { actionMenu } }
        .navigationDestination(item: $commitTarget) { target in
            DiffView(
                title: "Commit \(target.shortSha)",
                content: .commit(project: project, sha: target.sha))
        }
        .safeAreaInset(edge: .bottom) { bottomChrome }
        .sheet(isPresented: $showSettings) {
            SessionSettingsView(client: client, sessionID: sessionID)
        }
        .sheet(isPresented: $showQuestionSheet) {
            if let pending = model.pendingQuestion {
                QuestionSheet(
                    pending: pending,
                    onAnswerSingle: { optionIndex, text in
                        if optionIndex >= 0 { await model.answer(optionIndex: optionIndex) }
                        else { await model.answer(text: text) }
                    },
                    onAnswerBatch: { answers in await model.answerBatch(answers) }
                )
                // Tie the sheet's identity to the gate: if `pendingQuestion`
                // changes shape while the sheet is open (e.g. a reopened session's
                // resumed agent asks a differently-sized batch), a new `rowID`
                // rebuilds QuestionSheet with correctly-sized @State instead of
                // reusing stale `texts`/`selected` arrays and trapping on an
                // out-of-range index.
                .id(pending.rowID)
            }
        }
        // Present/dismiss the sheet as the pending gate opens and clears — the
        // event stream is the source of truth (answering here or elsewhere emits
        // `question_answered`, which clears `pendingQuestion`).
        .onChange(of: model.pendingQuestion?.rowID) { _, rowID in
            showQuestionSheet = (rowID != nil)
        }
        .alert(
            "Action failed",
            isPresented: Binding(
                get: { model.actionError != nil },
                set: { if !$0 { model.actionError = nil } }
            ),
            presenting: model.actionError
        ) { _ in
            Button("OK", role: .cancel) { model.actionError = nil }
        } message: { message in
            Text(message)
        }
        .confirmationDialog(
            "Stop this session?",
            isPresented: $showStopConfirm,
            titleVisibility: .visible
        ) {
            Button("Stop session", role: .destructive) {
                Task { await model.stopSession() }
            }
            Button("Cancel", role: .cancel) {}
        } message: {
            Text("This hard-terminates the agent — there is no resume.")
        }
        .task { model.start() }
        .onDisappear { model.stop() }
        .onChange(of: scenePhase) { _, phase in
            if phase == .active { model.reconnect() }
        }
    }

    // MARK: - Bottom chrome (banner + input bar)

    @ViewBuilder
    private var bottomChrome: some View {
        VStack(spacing: 0) {
            if model.mode == .live {
                pendingQuestionBanner
                phaseBanner
            } else {
                banner(
                    "Reopen this session to continue the conversation",
                    systemImage: "clock.arrow.circlepath",
                    tint: .secondary
                )
            }
            inputBar
        }
        .background(.bar)
    }

    /// When a question is pending but the sheet was swipe-dismissed, offer a way
    /// back in (the transcript row also still shows it as waiting).
    @ViewBuilder
    private var pendingQuestionBanner: some View {
        if model.pendingQuestion != nil, !showQuestionSheet {
            banner(
                "A question is waiting",
                systemImage: "questionmark.bubble.fill",
                tint: .orange,
                action: ("Answer", { showQuestionSheet = true })
            )
        }
    }

    @ViewBuilder
    private var phaseBanner: some View {
        switch model.phase {
        case .paused:
            banner(
                "Paused — send a steer or Resume",
                systemImage: "pause.circle.fill",
                tint: .orange,
                action: ("Resume", { Task { await model.resumeSession() } })
            )
        case .idle:
            banner("Session idle", systemImage: "moon.zzz.fill", tint: .secondary)
        case .error(let message, let retryable):
            let retryAction: (title: String, run: () -> Void)? =
                retryable ? ("Retry", { Task { await model.retry() } }) : nil
            banner(
                message.isEmpty ? "Session error" : "Error: \(message)",
                systemImage: "exclamationmark.triangle.fill",
                tint: .red,
                action: retryAction
            )
        case .stopped:
            banner("Session stopped", systemImage: "stop.circle.fill", tint: .secondary)
        case .running:
            EmptyView()
        }
    }

    private func banner(
        _ text: String,
        systemImage: String,
        tint: Color,
        action: (title: String, run: () -> Void)? = nil
    ) -> some View {
        HStack(spacing: 8) {
            Image(systemName: systemImage).foregroundStyle(tint)
            Text(text).font(.caption).foregroundStyle(.secondary)
            Spacer()
            if let action {
                Button(action.title, action: action.run)
                    .font(.caption.weight(.semibold))
                    .buttonStyle(.bordered)
                    .controlSize(.small)
            }
        }
        .padding(.horizontal, 12)
        .padding(.vertical, 6)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(tint.opacity(0.08))
    }

    private var inputBar: some View {
        VStack(alignment: .leading, spacing: 6) {
            if !pictures.isEmpty {
                ScrollView(.horizontal, showsIndicators: false) {
                    HStack(spacing: 8) {
                        ForEach(pictures) { picture in
                            ZStack(alignment: .topTrailing) {
                                Image(uiImage: picture.preview)
                                    .resizable().scaledToFill()
                                    .frame(width: 64, height: 64).clipped()
                                    .clipShape(RoundedRectangle(cornerRadius: 8))
                                Button {
                                    pictures.removeAll { $0.id == picture.id }
                                } label: {
                                    Image(systemName: "xmark.circle.fill")
                                        .symbolRenderingMode(.palette)
                                        .foregroundStyle(.white, .black.opacity(0.7))
                                }
                                .offset(x: 5, y: -5)
                                .accessibilityLabel("Remove picture")
                            }
                        }
                    }
                    .padding(.top, 5)
                }
                .accessibilityLabel("\(pictures.count) pictures attached")
            }
            HStack(spacing: 8) {
                PhotosPicker(
                    selection: $photoItems,
                    maxSelectionCount: max(1, Self.maxPictures - pictures.count),
                    matching: .images
                ) {
                    // The badge is the one honest signal that a pick actually
                    // landed; the thumbnail strip is easy to miss above the
                    // keyboard on a small screen.
                    Image(systemName: pictures.isEmpty
                        ? "photo.on.rectangle"
                        : "photo.badge.checkmark")
                        .font(.title3)
                        .foregroundStyle(pictures.isEmpty ? Color.accentColor : Color.green)
                        .opacity(loadingPictures ? 0 : 1)
                        .overlay {
                            if loadingPictures {
                                ProgressView().controlSize(.small)
                            }
                        }
                }
                .disabled(loadingPictures || PictureAttachments.isFull(current: pictures.count))
                .accessibilityLabel(pictures.isEmpty
                    ? "Add pictures"
                    : "Add pictures, \(pictures.count) attached")
                .onChange(of: photoItems) { _, items in
                    Task { await loadPictures(items) }
                }
                TextField("Message…", text: $draft, axis: .vertical)
                    .textFieldStyle(.roundedBorder)
                    .lineLimit(1...5)
                    .focused($composerFocused)
                    .onSubmit(send)
                Button(action: send) {
                    Image(systemName: "arrow.up.circle.fill")
                        .font(.title2)
                }
                .disabled(
                    loadingPictures ||
                    (draft.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty && pictures.isEmpty)
                )
            }
        }
        .padding(.horizontal, 12)
        .padding(.vertical, 8)
    }

    @MainActor
    private func loadPictures(_ items: [PhotosPickerItem]) async {
        // The `photoItems = []` reset below re-fires this `onChange` with an
        // empty selection. Without this guard that second pass overwrote
        // `pictures` with an empty array, so every attachment silently vanished
        // between picking it and sending — the thumbnails never even appeared.
        guard !items.isEmpty else { return }

        loadingPictures = true
        defer { loadingPictures = false; photoItems = [] }

        let room = PictureAttachments.room(current: pictures.count)
        guard room > 0 else {
            model.actionError = "You can attach up to \(Self.maxPictures) pictures."
            return
        }

        var loaded: [DraftPicture] = []
        do {
            for (index, item) in items.prefix(room).enumerated() {
                guard let source = try await item.loadTransferable(type: Data.self),
                      let uiImage = UIImage(data: source) else {
                    throw PictureError.unreadable
                }
                // Normalize to bounded JPEG so HEIC and other Photos formats
                // have a model-supported wire type, and so a 48MP camera roll
                // original cannot blow the daemon's per-image size limit.
                guard let data = Self.normalizedJPEG(uiImage) else {
                    throw PictureError.tooLarge
                }
                loaded.append(DraftPicture(
                    image: MessageImage(
                        data: data,
                        mediaType: "image/jpeg",
                        filename: "photo-\(pictures.count + index + 1).jpg"),
                    preview: uiImage))
            }
            // Merge rather than replace: each round starts from a cleared
            // selection, so replacing would drop earlier picks (and an empty
            // round would wipe the draft entirely — see PictureAttachments).
            pictures = PictureAttachments.merged(existing: pictures, adding: loaded)
        } catch {
            // Keep whatever was already attached; only this round is dropped.
            model.actionError = error.localizedDescription
        }
    }

    /// Downscale to a sane long edge, then step the JPEG quality down until the
    /// encoding fits the per-image cap. Drawing through a renderer also bakes in
    /// the EXIF orientation, so a portrait photo doesn't reach the model sideways.
    private static func normalizedJPEG(_ image: UIImage) -> Data? {
        let maxEdge: CGFloat = 2048
        let longEdge = max(image.size.width, image.size.height)
        let target: UIImage
        if longEdge > maxEdge, longEdge > 0 {
            let scale = maxEdge / longEdge
            let size = CGSize(
                width: (image.size.width * scale).rounded(),
                height: (image.size.height * scale).rounded())
            let format = UIGraphicsImageRendererFormat.default()
            format.scale = 1
            target = UIGraphicsImageRenderer(size: size, format: format).image { _ in
                image.draw(in: CGRect(origin: .zero, size: size))
            }
        } else {
            target = image
        }
        for quality in [0.85, 0.7, 0.55, 0.4] as [CGFloat] {
            if let data = target.jpegData(compressionQuality: quality),
               data.count <= maxPictureBytes {
                return data
            }
        }
        return nil
    }

    private func send() {
        let text = draft
        let images = pictures.map(\.image)
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty || !images.isEmpty else { return }
        draft = ""
        pictures = []
        Task { await model.send(text: text, images: images) }
    }

    private enum PictureError: LocalizedError {
        case unreadable, tooLarge
        var errorDescription: String? {
            switch self {
            case .unreadable: return "One of the selected pictures could not be read."
            case .tooLarge: return "A selected picture is too large to send, even after downscaling."
            }
        }
    }

    private var transcript: some View {
        ScrollView {
            // Keep transcript rows eagerly mounted. A LazyVStack can lose its
            // estimated content geometry when the last row changes height many
            // times per second (the streaming tail) while ScrollViewReader also
            // keeps that row pinned. The resulting stale offset presents as an
            // empty transcript until a manual scroll forces another layout pass.
            // Session rows already collapse heavy tool/thinking details, so the
            // predictable geometry is worth the modest eager-layout cost here.
            VStack(alignment: .leading, spacing: 10) {
                if model.durableRows.isEmpty, model.liveTail == nil, model.state == .loading {
                    ProgressView().frame(maxWidth: .infinity).padding(.top, 40)
                }
                // Keep immutable history separate from the rapidly-changing tail.
                // Building `durableRows + [liveTail]` every 100ms made SwiftUI diff
                // the entire transcript for every snapshot.
                ForEach(model.durableRows) { row in
                    TranscriptRowView(row: row) { sha in
                        commitTarget = CommitDiffTarget(sha: sha)
                    }
                    .equatable()
                    .id(row.id)
                }
                if let liveTail = model.liveTail {
                    // Intentionally not `.equatable()`: this stable-id subtree
                    // must receive each snapshot so TextKit can append its suffix.
                    TranscriptRowView(row: liveTail)
                        .id(liveTail.id)
                } else if model.isAwaitingAgentActivity {
                    workingRow
                        .id("agent-working")
                }
                // A small marker row tells us geometrically when the latest
                // content is visible. With this eager VStack the marker remains
                // mounted while offscreen, so lifecycle callbacks cannot answer
                // that question reliably.
                Color.clear
                    .frame(height: 1)
                    .id(Self.bottomAnchor)
                    .background {
                        GeometryReader { geometry in
                            Color.clear.preference(
                                key: TranscriptBottomPreferenceKey.self,
                                value: geometry.frame(
                                    in: .named(Self.transcriptCoordinateSpace)).maxY)
                        }
                    }
            }
            .padding()
        }
        .coordinateSpace(name: Self.transcriptCoordinateSpace)
        .onPreferenceChange(TranscriptBottomPreferenceKey.self) { bottomY in
            let tolerance: CGFloat = 8
            isLatestVisible = bottomY <= transcriptViewportHeight + tolerance
            // Only a user's drag can opt out of follow mode. Content growth while
            // pinned can briefly move the marker below the viewport before the
            // explicit scroll request settles, and must not look like scrollback.
            if isDraggingTranscript, !isLatestVisible {
                stopFollowingLatest()
            }
        }
        .simultaneousGesture(
            DragGesture(minimumDistance: 4)
                .onChanged { value in
                    if !isDraggingTranscript { isDraggingTranscript = true }
                    // At gesture recognition time the geometry preference can lag
                    // the finger by one layout pass. A downward swipe is explicitly
                    // toward older content, so it must win even before that pass.
                    if !isLatestVisible || value.translation.height > 0 {
                        stopFollowingLatest()
                    }
                }
                .onEnded { _ in
                    // Deceleration continues after this callback. Follow mode was
                    // already disabled as soon as the drag moved off the live edge.
                    isDraggingTranscript = false
                }
        )
        .background {
            GeometryReader { geometry in
                Color.clear
                    .onAppear { transcriptViewportHeight = geometry.size.height }
                    .onChange(of: geometry.size.height) { _, height in
                        transcriptViewportHeight = height
                    }
            }
        }
        // Do not use `.defaultScrollAnchor(.bottom)` here. SwiftUI also consults
        // that anchor on content-size changes, which moves the viewport whenever
        // the live tail grows even while the user is reading scrollback. Initial
        // and subsequent live-edge positioning are both handled explicitly by
        // `requestScrollToLatest` while follow mode is enabled.
    }

    /// Immediate acknowledgement after StartSession/SendInput, shown until the
    /// event stream produces the first meaningful piece of agent activity.
    private var workingRow: some View {
        HStack(spacing: 10) {
            ProgressView()
                .controlSize(.small)
            Text("Agent is working…")
                .font(.subheadline)
                .foregroundStyle(.secondary)
        }
        .padding(.horizontal, 12)
        .padding(.vertical, 10)
        .background(Color(.secondarySystemBackground), in: RoundedRectangle(cornerRadius: 14))
        .frame(maxWidth: .infinity, alignment: .leading)
        .accessibilityElement(children: .combine)
        .accessibilityLabel("Agent is working")
    }

    private func stopFollowingLatest() {
        guard isFollowingLatest else { return }
        isFollowingLatest = false
        // Invalidate a post-layout or keyboard-settle request that was queued
        // while the transcript was still following the live edge.
        scrollToken.value &+= 1
    }

    private func requestScrollToLatest(proxy: ScrollViewProxy) {
        guard isFollowingLatest else { return }
        scrollToken.value &+= 1
        let request = scrollToken.value
        Task { @MainActor in
            // Let LazyVStack, the keyboard safe area, and the composer all
            // finish the current layout pass. A newer request supersedes us.
            await Task.yield()
            guard request == scrollToken.value, isFollowingLatest else { return }
            proxy.scrollTo(Self.bottomAnchor, anchor: .bottom)
            // Keyboard presentation is animated over several layout passes;
            // settle once more after it reaches its final safe-area height.
            if composerFocused {
                try? await Task.sleep(nanoseconds: 300_000_000)
                guard request == scrollToken.value, isFollowingLatest else { return }
                proxy.scrollTo(Self.bottomAnchor, anchor: .bottom)
            }
        }
    }

    private func jumpToLatestPill(proxy: ScrollViewProxy) -> some View {
        Button {
            isFollowingLatest = true
            proxy.scrollTo(Self.bottomAnchor, anchor: .bottom)
        } label: {
            Label("Jump to latest", systemImage: "arrow.down")
                .font(.subheadline.weight(.semibold))
                .padding(.horizontal, 14)
                .padding(.vertical, 8)
                .background(.thinMaterial, in: Capsule())
                .overlay(Capsule().strokeBorder(.quaternary))
        }
        .buttonStyle(.plain)
    }

    /// A two-line inline title: the session's name over its project. An inline
    /// `navigationTitle` alone can only show one line, and "which project is
    /// this?" is the question a cross-project feed makes constant.
    @ToolbarContentBuilder
    private var titleToolbar: some ToolbarContent {
        ToolbarItem(placement: .principal) {
            VStack(spacing: 0) {
                Text(title)
                    .font(.headline)
                    .lineLimit(1)
                    .truncationMode(.middle)
                if !project.isEmpty {
                    Text(project)
                        .font(.caption2)
                        .foregroundStyle(.secondary)
                        .lineLimit(1)
                }
            }
            .frame(maxWidth: 220)
            .accessibilityElement(children: .combine)
        }
    }

    @ToolbarContentBuilder
    private var statusToolbar: some ToolbarContent {
        ToolbarItem(placement: .topBarTrailing) {
            switch model.state {
            case .streaming:
                Label("Live", systemImage: "dot.radiowaves.left.and.right")
                    .labelStyle(.iconOnly)
                    .foregroundStyle(.green)
            case .reconnecting, .loading:
                ProgressView()
            case .failed:
                Image(systemName: "exclamationmark.triangle.fill")
                    .foregroundStyle(.orange)
            case .idle, .finished:
                EmptyView()
            }
        }
    }

    /// One overflow menu rather than a row of glyphs: settings plus the
    /// interrupt / resume / stop controls.
    @ToolbarContentBuilder
    private var actionMenu: some ToolbarContent {
        ToolbarItem(placement: .topBarTrailing) {
            Menu {
                Button {
                    showSettings = true
                } label: {
                    Label("Session settings", systemImage: "gearshape")
                }
                Divider()
                Button {
                    Task { await model.interrupt() }
                } label: {
                    Label("Interrupt", systemImage: "pause.circle")
                }
                Button {
                    Task { await model.resumeSession() }
                } label: {
                    Label("Resume", systemImage: "play.circle")
                }
                Divider()
                Button(role: .destructive) {
                    showStopConfirm = true
                } label: {
                    Label("Stop…", systemImage: "stop.circle")
                }
            } label: {
                Label("Session actions", systemImage: "ellipsis.circle")
            }
        }
    }
}

/// Carries the transcript tail's vertical position out of its scroll content so
/// follow mode can distinguish a user reading scrollback from a tail that merely
/// moved during live layout.
private struct TranscriptBottomPreferenceKey: PreferenceKey {
    static let defaultValue = CGFloat.greatestFiniteMagnitude
    static func reduce(value: inout CGFloat, nextValue: () -> CGFloat) {
        value = nextValue()
    }
}

/// Renders a single ``TranscriptRow``. Bubbles for messages; collapsed,
/// tappable disclosure rows for thinking and tool calls; compact system rows.
private struct TranscriptRowView: View, Equatable {
    let row: TranscriptRow
    /// Called with the commit sha when a `commit_made` row is tapped.
    var onOpenCommit: (String) -> Void = { _ in }

    /// The callback is stable for a transcript row's lifetime; row payload is the
    /// only input that should invalidate its subtree. This keeps old MarkdownText
    /// rows from being reparsed whenever the live tail changes.
    static func == (lhs: Self, rhs: Self) -> Bool { lhs.row == rhs.row }

    var body: some View {
        switch row.kind {
        case .userMessage(let text):
            bubble(text: text, isUser: true)
        case .modelMessage(let text):
            bubble(text: text, isUser: false, actor: row.actor)
        case .finalReport(let text):
            finalReport(text)
        case .thinking(let text):
            ExpandableRow(
                title: "Thinking",
                systemImage: "brain",
                tint: .purple,
                detail: text
            )
        case .tool(let name, let status, let args, let output):
            ToolRowView(name: name, status: status, args: args, output: output)
        case .question(let prompt, let options, let answer):
            QuestionRowView(prompt: prompt, options: options, answer: answer)
        case .system(let text):
            systemRow(text)
        case .commit(let text, let sha):
            commitRow(text, sha: sha)
        case .liveTail(let text):
            liveTail(
                text,
                append: row.liveAppend,
                appendBaseUTF8: row.liveAppendBaseUTF8
            )
        }
    }

    private func bubble(text: String, isUser: Bool, actor: String = "") -> some View {
        HStack {
            if isUser { Spacer(minLength: 40) }
            VStack(alignment: isUser ? .trailing : .leading, spacing: 2) {
                if !isUser, !actor.isEmpty {
                    Text(actor).font(.caption2).foregroundStyle(.secondary)
                }
                Group {
                    if isUser {
                        // User messages stay plain text — they were typed, not
                        // authored in markdown.
                        Text(text.isEmpty ? " " : text)
                    } else {
                        // Agent messages render as markdown (headings, lists,
                        // inline styles, fenced code blocks).
                        MarkdownText(text: text.isEmpty ? " " : text)
                    }
                }
                .textSelection(.enabled)
                .padding(.horizontal, 12)
                .padding(.vertical, 8)
                .background(
                    isUser ? Color.accentColor.opacity(0.85) : Color(.secondarySystemBackground),
                    in: RoundedRectangle(cornerRadius: 14)
                )
                .foregroundStyle(isUser ? .white : .primary)
            }
            if !isUser { Spacer(minLength: 40) }
        }
    }

    /// The finish message is the primary result of a session, not a lifecycle
    /// footnote: keep it always expanded, render its Markdown structure, and give
    /// it a distinct success card that remains easy to find in a long transcript.
    private func finalReport(_ text: String) -> some View {
        VStack(alignment: .leading, spacing: 10) {
            Label("Finished", systemImage: "checkmark.circle.fill")
                .font(.headline)
                .foregroundStyle(.green)
            MarkdownText(text: text)
                .textSelection(.enabled)
                .frame(maxWidth: .infinity, alignment: .leading)
        }
        .padding(14)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(Color.green.opacity(0.09), in: RoundedRectangle(cornerRadius: 14))
        .overlay {
            RoundedRectangle(cornerRadius: 14)
                .stroke(Color.green.opacity(0.28), lineWidth: 1)
        }
        .accessibilityElement(children: .contain)
        .accessibilityLabel("Session finished")
    }

    private func systemRow(_ text: String) -> some View {
        HStack(spacing: 6) {
            Image(systemName: "circle.fill").font(.system(size: 4)).foregroundStyle(.tertiary)
            Text(text)
                .font(.caption)
                .foregroundStyle(.secondary)
                .frame(maxWidth: .infinity, alignment: .leading)
        }
    }

    /// A commit row: like a system row, but tappable to drill into the commit's
    /// diff when a sha is present. Without a sha it degrades to a plain row.
    @ViewBuilder
    private func commitRow(_ text: String, sha: String) -> some View {
        if sha.isEmpty {
            systemRow(text)
        } else {
            Button {
                onOpenCommit(sha)
            } label: {
                HStack(spacing: 6) {
                    Image(systemName: "arrow.triangle.branch")
                        .font(.caption2)
                        .foregroundStyle(.blue)
                    Text(text)
                        .font(.caption)
                        .foregroundStyle(.secondary)
                        .frame(maxWidth: .infinity, alignment: .leading)
                    Image(systemName: "chevron.right")
                        .font(.caption2)
                        .foregroundStyle(.tertiary)
                }
            }
            .buttonStyle(.plain)
        }
    }

    private func liveTail(
        _ text: String,
        append: String?,
        appendBaseUTF8: Int?
    ) -> some View {
        HStack {
            VStack(alignment: .leading, spacing: 2) {
                HStack(spacing: 4) {
                    ProgressView().scaleEffect(0.6)
                    Text("streaming").font(.caption2).foregroundStyle(.secondary)
                }
                // Unlike SwiftUI.Text, this keeps one TextKit storage/layout tree
                // alive and appends the new suffix for ordinary growing snapshots.
                // Replacing an ever-longer Text at 10 Hz repeatedly shaped and laid
                // out the full response, producing quadratic-feeling slowdown.
                IncrementalStreamingText(
                    text: text,
                    append: append,
                    appendBaseUTF8: appendBaseUTF8
                )
                .padding(.horizontal, 12)
                    .padding(.vertical, 8)
                    .background(Color(.secondarySystemBackground), in: RoundedRectangle(cornerRadius: 14))
                    .foregroundStyle(.primary)
            }
            Spacer(minLength: 40)
        }
    }
}

/// A non-scrolling, selectable TextKit view optimized for snapshot-style model
/// output. Normal snapshots extend the previous text, so mutate NSTextStorage by
/// only the suffix and let TextKit incrementally lay out the addition. A retry or
/// other non-prefix replacement falls back to replacing the complete value.
private struct IncrementalStreamingText: UIViewRepresentable {
    let text: String
    let append: String?
    let appendBaseUTF8: Int?

    final class Coordinator {
        var renderedText = ""
        var renderedUTF8Count = 0
        var font: UIFont?
    }

    func makeCoordinator() -> Coordinator { Coordinator() }

    func makeUIView(context: Context) -> UITextView {
        let view = UITextView()
        view.backgroundColor = .clear
        view.isEditable = false
        view.isSelectable = true
        view.isScrollEnabled = false
        view.textContainerInset = .zero
        view.textContainer.lineFragmentPadding = 0
        view.setContentCompressionResistancePriority(.defaultLow, for: .horizontal)
        view.setContentHuggingPriority(.required, for: .vertical)
        return view
    }

    func updateUIView(_ view: UITextView, context: Context) {
        let font = UIFont.preferredFont(forTextStyle: .body)
        let foreground = UIColor.label
        let attributes: [NSAttributedString.Key: Any] = [
            .font: font,
            .foregroundColor: foreground,
        ]
        let coordinator = context.coordinator
        var nextUTF8Count = coordinator.renderedUTF8Count

        if coordinator.font != font {
            // Dynamic Type/style changes are rare and legitimately require a
            // complete relayout; streamed snapshots normally stay on append path.
            view.attributedText = NSAttributedString(string: text, attributes: attributes)
            nextUTF8Count = text.utf8.count
        } else if let append,
                  let appendBaseUTF8,
                  appendBaseUTF8 == coordinator.renderedUTF8Count {
            // Fast path from a daemon-provided verified base offset: no growing
            // prefix/count scan and no reconstruction of the accumulated string.
            if !append.isEmpty {
                view.textStorage.append(NSAttributedString(string: append, attributes: attributes))
            }
            nextUTF8Count = appendBaseUTF8 + append.utf8.count
        } else if text.hasPrefix(coordinator.renderedText) {
            // Compatibility path for older daemons that only send snapshots.
            let suffix = text.dropFirst(coordinator.renderedText.count)
            if !suffix.isEmpty {
                view.textStorage.append(NSAttributedString(string: String(suffix), attributes: attributes))
            }
            nextUTF8Count = text.utf8.count
        } else if text != coordinator.renderedText {
            // Retry/reset, lossy hint gap, or another non-prefix replacement.
            view.attributedText = NSAttributedString(string: text, attributes: attributes)
            nextUTF8Count = text.utf8.count
        }

        coordinator.renderedText = text
        coordinator.renderedUTF8Count = nextUTF8Count
        coordinator.font = font
    }

    func sizeThatFits(
        _ proposal: ProposedViewSize,
        uiView: UITextView,
        context: Context
    ) -> CGSize? {
        guard let width = proposal.width else { return nil }
        let fitted = uiView.sizeThatFits(
            CGSize(width: width, height: .greatestFiniteMagnitude))
        return CGSize(width: width, height: fitted.height)
    }
}

